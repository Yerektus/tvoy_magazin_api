"""Проверка штрихкода по контрольной цифре.

У EAN-8, UPC-A и EAN-13 последняя цифра вычисляется из остальных, поэтому
опечатку и чужое число видно без всякой базы. Нам это нужно затем, что модель
иногда принимает за штрихкод номенклатурный номер из соседней колонки:

    80843519      → не сходится   (номенклатурный номер поставщика)
    4870145005545 → сходится      (настоящий штрихкод)

Неверный штрихкод хуже пустого. Пустая строка честно уйдёт на сопоставление по
названию, а неверный либо не найдёт ничего, либо найдёт чужой товар — и тот
молча уедет в приёмку.
"""

# Длины, у которых есть контрольная цифра: EAN-8, UPC-A, EAN-13 и коробочный
# GTIN-14. Всё остальное — внутренний код поставщика, а не штрихкод.
LENGTHS = (8, 12, 13, 14)


def valid(code: str) -> bool:
    """Сходится ли контрольная цифра. Не цифры или чужая длина — не штрихкод."""

    digits = (code or '').strip()

    if not digits.isdigit() or len(digits) not in LENGTHS:
        return False

    numbers = [int(char) for char in digits]

    # Веса считаем справа налево: ближайшая к контрольной цифра всегда тройка,
    # дальше по очереди. Так одна формула подходит всем длинам сразу.
    checksum = sum(
        digit * (3 if position % 2 == 0 else 1)
        for position, digit in enumerate(reversed(numbers[:-1]))
    )

    return (10 - checksum % 10) % 10 == numbers[-1]
