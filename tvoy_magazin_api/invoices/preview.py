"""Обработка снимка накладной: сжатие и поворот «как читать».

Телефон снимает в 3000×4000 и тяжелее: и в модель это лишние токены (платим
за них), и в браузере лишние мегабайты трафика. Поэтому ужимаем любой формат,
не только HEIC, — длинная сторона PREVIEW_SIZE читается моделью не хуже
оригинала, весит же вчетверо-впятеро меньше.

Айфон вдобавок снимает в HEIC: Safari такой файл рисует, а Chrome и
Firefox — нет, и в просмотрщике вместо накладной пустота. Часть моделей на
HEIC вдобавок отвечает «это не картинка». Перевод в JPEG закрывает обе беды.

Второе — лист на фото часто лежит боком: снимают, не поворачивая телефон, и
накладная открывается повёрнутой на 90 градусов. Читать её так неудобно.
Угол берём у самой модели (`rotation` в ответе): она и так смотрит на это
фото, а прочитав текст, точно знает, где верх. Геометрией это не решается —
хоть по контурам, хоть по строкам текста 0 градусов от 180 не отличить, для
этого нужно понимать написанное.

Обрезать лист по краям тут когда-то пробовали, через OpenCV, и от этого
отказались: на настоящих фото магазина документ занимает почти весь кадр,
искать в нём четырёхугольник нечего. Детектор вместо листа цеплялся за рамку
таблицы внутри и срезал шапку, номер, дату, «Итого» и рукописные правки —
то есть ровно то, ради чего накладную и снимают. На 61 фото это ни разу не
помогло и в 15 случаях испортило бы документ.

Конвертируем прямо в процессе, через Pillow с плагином pillow-heif. Раньше
звали внешнюю утилиту — `sips`, `heif-convert` или `magick`, — и на маке это
работало, а в контейнере хостинга не оказалось ни одной: превью тихо не
появлялось, и всё ломалось разом. Колесо pillow-heif несёт libheif с собой,
поэтому от содержимого образа мы больше не зависим.
"""

import io
import logging
from pathlib import Path

import pillow_heif
from PIL import Image, ImageOps, UnidentifiedImageError

logger = logging.getLogger(__name__)

# Длинная сторона снимка: мелкий текст накладной должен остаться читаемым.
# Оригинал с телефона вчетверо тяжелее, а платим мы и за токены изображения.
PREVIEW_SIZE = 2200
QUALITY = 85

# PDF сюда не входит: Pillow его не откроет, а в модель он и так уходит как
# application/pdf, без сжатия.
NEEDS_PREVIEW = ('.jpg', '.jpeg', '.png', '.webp', '.heic', '.heif')

# Поворот по часовой стрелке — в то, чем это делает Pillow. Свои ROTATE_*
# крутят против часовой, поэтому 90 и 270 меняются местами.
TURNS = {
    90: Image.Transpose.ROTATE_270,
    180: Image.Transpose.ROTATE_180,
    270: Image.Transpose.ROTATE_90,
}

# Где на снимке лежит верхний край документа — и на сколько градусов по часовой
# стрелке повернуть кадр, чтобы этот край оказался сверху.
#
# Спрашиваем у модели именно сторону, а не готовый угол: угол она путает —
# «повернуть на 90» читает как «документ повёрнут на 90», а это обратное, и
# накладная встаёт вверх ногами. Сторона же — то, что прямо видно на кадре.
UPRIGHT_TURNS = {'top': 0, 'right': 270, 'bottom': 180, 'left': 90}

# Учит Pillow открывать HEIC — иначе он такой файл просто не узнает.
pillow_heif.register_heif_opener()


def needed_for(name: str) -> bool:
    return name.lower().endswith(NEEDS_PREVIEW)


def compress(source: Path) -> bytes | None:
    """Сжатый JPEG или None, если сжимать нечего либо файл не открылся.

    «Нечего» — это уже готовый снимок: разбор перезапускают кнопкой «распознать
    заново», и без этой проверки фотография пережималась бы на каждом заходе,
    теряя в качестве.
    """

    try:
        with Image.open(source) as image:
            if _ready(image):
                return None

            # Сначала уменьшаем, потом поворачиваем — не наоборот. Поворот
            # делает копию картинки целиком, и на снимке с телефона это лишние
            # 86 МБ: 381 МБ пика против 295 МБ. Результат байт в байт тот же —
            # рамка квадратная, и сторона, по которой ужимаем, от поворота не
            # зависит.
            image.thumbnail((PREVIEW_SIZE, PREVIEW_SIZE))

            # Телефон пишет поворот в EXIF, а не в самих пикселях: без этого
            # накладная открывается лёжа на боку.
            ImageOps.exif_transpose(image, in_place=True)

            return _jpeg(image.convert('RGB'))
    except (OSError, UnidentifiedImageError, ValueError) as error:
        # Битый файл — не повод ронять разбор: накладная откроется без снимка.
        logger.warning('Не удалось обработать снимок %s: %s', source.name, error)
        return None


def upright(source: Path, degrees: int) -> bytes | None:
    """Тот же снимок, повёрнутый на `degrees` по часовой стрелке.

    Углы кратны 90, поэтому поворот здесь — перестановка пикселей: ничего не
    интерполируется и не размывается. None — угол нулевой или незнакомый
    (крутить нечего) либо файл не открылся.
    """

    turn = TURNS.get(degrees)

    if turn is None:
        return None

    try:
        with Image.open(source) as image:
            return _jpeg(image.transpose(turn))
    except (OSError, UnidentifiedImageError, ValueError) as error:
        logger.warning('Не удалось повернуть снимок %s: %s', source.name, error)
        return None


def _ready(image: Image.Image) -> bool:
    """Снимок уже такой, каким мы его сделали бы: JPEG в размер и без EXIF-поворота."""

    # 0x0112 — тег Orientation. Единица означает «пиксели уже лежат правильно».
    return (
        image.format == 'JPEG'
        and max(image.size) <= PREVIEW_SIZE
        and image.getexif().get(0x0112, 1) == 1
    )


def _jpeg(image: Image.Image) -> bytes:
    buffer = io.BytesIO()
    image.save(buffer, 'JPEG', quality=QUALITY, optimize=True)

    return buffer.getvalue()
